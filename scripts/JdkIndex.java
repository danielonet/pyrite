import java.lang.module.ModuleDescriptor;
import java.lang.module.ModuleFinder;
import java.lang.reflect.Modifier;
import java.net.URI;
import java.nio.file.*;
import java.util.*;
import java.util.stream.*;

/**
 * Prints src/translator/imports/jdkClasses.ts: every public top-level class in the packages the
 * java.se modules export, grouped by package. Run with `node scripts/build-jdk-index.js`.
 */
public class JdkIndex {
    public static void main(String[] args) throws Exception {
        ModuleFinder finder = ModuleFinder.ofSystem();
        Set<String> modules = new TreeSet<>();
        Deque<String> todo = new ArrayDeque<>(List.of("java.se"));
        while (!todo.isEmpty()) {
            String name = todo.pop();
            if (!modules.add(name)) continue;
            ModuleDescriptor d = finder.find(name).orElseThrow().descriptor();
            for (ModuleDescriptor.Requires r : d.requires()) if (r.name().startsWith("java.")) todo.push(r.name());
        }
        Map<String, String> packageModule = new TreeMap<>();
        for (String m : modules) {
            for (ModuleDescriptor.Exports e : finder.find(m).orElseThrow().descriptor().exports()) {
                if (!e.isQualified()) packageModule.put(e.source(), m);
            }
        }
        FileSystem jrt = FileSystems.getFileSystem(URI.create("jrt:/"));
        Map<String, List<String>> classes = new TreeMap<>();
        for (Map.Entry<String, String> e : packageModule.entrySet()) {
            Path dir = jrt.getPath("/modules", e.getValue(), e.getKey().replace('.', '/'));
            if (!Files.isDirectory(dir)) continue;
            List<String> names = new ArrayList<>();
            try (Stream<Path> files = Files.list(dir)) {
                for (Path f : files.sorted().toList()) {
                    String file = f.getFileName().toString();
                    if (!file.endsWith(".class") || file.contains("$") || file.equals("module-info.class") || file.equals("package-info.class")) continue;
                    String simple = file.substring(0, file.length() - 6);
                    try {
                        Class<?> c = Class.forName(e.getKey() + "." + simple, false, ClassLoader.getPlatformClassLoader());
                        if (Modifier.isPublic(c.getModifiers())) names.add(simple);
                    } catch (Throwable ignored) {
                        // not loadable here: leave it out
                    }
                }
            }
            if (!names.isEmpty()) classes.put(e.getKey(), names);
        }
        StringBuilder out = new StringBuilder();
        out.append("/**\n * Every public top-level class in the packages the java.se modules export (JDK ")
           .append(Runtime.version().feature())
           .append("), by package.\n * Generated by scripts/build-jdk-index.js - do not edit by hand.\n */\n");
        out.append("export const JDK_FEATURE_VERSION = ").append(Runtime.version().feature()).append(";\n\n");
        out.append("export const JDK_CLASSES: Record<string, string> = {\n");
        for (Map.Entry<String, List<String>> e : classes.entrySet()) {
            out.append("  '").append(e.getKey()).append("': '").append(String.join(" ", e.getValue())).append("',\n");
        }
        out.append("};\n");
        System.out.print(out);
    }
}
